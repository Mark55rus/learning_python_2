# Подвиг 8. На вход программе подаются целые числа, записанные в одну строку через пробел. 
# Необходимо их прочитать и сохранить в кортеже. 
# Затем, в кортеже найти и вывести в одну строчку через пробел (по порядку) 
# все индексы неуникальных (повторяющихся) значений.

numbers = tuple(map(int, input().split()))

repeating = tuple(i for i, num in enumerate(numbers) if numbers.count(num) > 1)

print(*repeating)
