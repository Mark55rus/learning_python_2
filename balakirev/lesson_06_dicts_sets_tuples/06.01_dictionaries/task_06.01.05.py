# Подвиг 3. На вход программе подаются данные в формате ключ=значение,
# записанные через пробел. Значениями здесь являются целые числа (см. пример ниже).
# Необходимо прочитать строку с этими данными и на их основе сформировать словарь d,
# используя функцию dict(). Результирующий словарь вывести на экран командой:
# print(*sorted(d.items()))

lst = input().split()

new_lst = [[k, int(v)] for para in lst for k, v in [para.split('=')]]

d = dict(new_lst)
print(*sorted(d.items()))
