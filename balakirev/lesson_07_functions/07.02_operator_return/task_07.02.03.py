# Подвиг 1. Объявите в программе функцию с именем get_sq,
# которая имеет один параметр (принимает вещественное число).
# В теле функции значение параметра возводится в квадрат и возвращается функцией.
# После объявления функции прочитайте (с помощью функции input)
# вещественное число из входного потока и вызовите функцию с прочитанным значением.
# Выведите на экран число, которое возвратила функция.

def get_sq(num):
    result = num ** 2
    return result


print(get_sq(float(input())))
